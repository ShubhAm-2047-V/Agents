"""
pdf_generator.py
Generates polished, executive PDF research and comparison reports.
Uses ReportLab with custom styling, headers, footers, and structured layout including professional tables.
"""

import os
import re
from datetime import datetime
from reportlab.lib.pagesizes import letter
from reportlab.lib import colors
from reportlab.platypus import (
    SimpleDocTemplate,
    Paragraph,
    Spacer,
    HRFlowable,
    Table,
    TableStyle,
    KeepTogether
)
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.pdfgen import canvas


class NumberedCanvas(canvas.Canvas):
    """Adds professional running header and footer with page numbers."""

    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self._saved_page_states = []

    def showPage(self):
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_page_decorations(num_pages)
            super().showPage()
        super().save()

    def draw_page_decorations(self, page_count):
        self.saveState()
        self.setFont("Helvetica", 8)
        self.setFillColor(colors.HexColor("#718096"))

        # Header (pages after page 1)
        if self._pageNumber > 1:
            self.drawString(45, 750, "Orion AI Web Search & Intelligence Report")
            self.setStrokeColor(colors.HexColor("#E2E8F0"))
            self.setLineWidth(0.5)
            self.line(45, 742, letter[0] - 45, 742)

        # Footer
        footer_text = f"Generated by Orion Web Search Agent  |  Page {self._pageNumber} of {page_count}"
        self.drawRightString(letter[0] - 45, 30, footer_text)
        self.drawString(45, 30, datetime.now().strftime("%B %d, %Y"))
        self.setStrokeColor(colors.HexColor("#E2E8F0"))
        self.setLineWidth(0.5)
        self.line(45, 42, letter[0] - 45, 42)

        self.restoreState()


def _clean_markdown_for_reportlab(text):
    """Converts common Markdown patterns and sanitizes Unicode glyphs unsupported by standard PDF fonts."""
    # Replace Rupee symbol with INR / Rs.
    text = text.replace('₹', 'Rs. ')
    
    # Strip emojis and special unicode symbols that render as black squares
    text = re.sub(r'[\U00010000-\U0010ffff]', '', text)
    text = re.sub(r'[⚖📊🎯🔍🏆📌⚡📋🌐📰🔗💡✅❌⚠️🔬•◦━─]', '', text).strip()

    # Convert bold **text** to <b>text</b>
    text = re.sub(r'\*\*(.+?)\*\*', r'<b>\1</b>', text)
    # Convert italic *text* or _text_ to <i>text</i>
    text = re.sub(r'(?<!\*)\*([^*]+?)\*(?!\*)', r'<i>\1</i>', text)
    # Escape standalone & if not part of an XML entity
    text = re.sub(r'&(?!(amp|lt|gt|quot|apos);)', '&amp;', text)
    return text.strip()


def _extract_items_from_query(query):
    """Extracts item names from a comparison query like 'moto edge 70 and moto edge 70 fusion'."""
    clean = re.sub(r'^(compare|difference between|versus|vs)\s+', '', query, flags=re.IGNORECASE).strip()
    parts = re.split(r'\s+(?:and|vs|versus|to)\s+', clean, flags=re.IGNORECASE)
    if len(parts) >= 2:
        return parts[0].strip().title(), parts[1].strip().title()
    return "Option A", "Option B"


def _build_table_from_markdown_lines(table_lines, styles, page_width=522):
    """Parses a markdown table into a ReportLab Table flowable with wrapped Paragraph cells."""
    rows = []
    for line in table_lines:
        line = line.strip()
        if not line or not line.startswith('|'):
            continue
        # Skip divider rows like |---|---|
        if re.match(r'^\|[\s\-:|]+\|$', line):
            continue
        cells = [c.strip() for c in line.split('|')[1:-1]]
        if cells:
            rows.append(cells)

    if not rows:
        return None

    num_cols = max(len(r) for r in rows)
    # Normalize row lengths
    for r in rows:
        while len(r) < num_cols:
            r.append("")

    # Determine column widths
    if num_cols == 3:
        col_widths = [120, 201, 201]
    elif num_cols == 2:
        col_widths = [160, 362]
    elif num_cols == 4:
        col_widths = [100, 140, 140, 142]
    else:
        w = page_width / num_cols
        col_widths = [w] * num_cols

    # Build cell paragraph elements
    table_data = []
    for row_idx, row in enumerate(rows):
        formatted_row = []
        is_header = (row_idx == 0)
        for cell in row:
            clean_cell = _clean_markdown_for_reportlab(cell)
            if is_header:
                p = Paragraph(f"<b>{clean_cell}</b>", styles['TableHeader'])
            else:
                p = Paragraph(clean_cell, styles['TableCell'])
            formatted_row.append(p)
        table_data.append(formatted_row)

    t = Table(table_data, colWidths=col_widths)
    t.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor("#1A365D")),
        ('ALIGN', (0, 0), (-1, -1), 'LEFT'),
        ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
        ('TOPPADDING', (0, 0), (-1, -1), 4),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 4),
        ('LEFTPADDING', (0, 0), (-1, -1), 6),
        ('RIGHTPADDING', (0, 0), (-1, -1), 6),
        ('ROWBACKGROUNDS', (0, 1), (-1, -1), [colors.HexColor("#F8FAFC"), colors.white]),
        ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor("#CBD5E0")),
    ]))
    return t


def _convert_spec_bullets_to_table(bullets, item_a, item_b, styles):
    """Converts lines like '• Display: 6.7 in vs 6.8 in' into a structured Table."""
    rows = [["Specification / Feature", item_a, item_b]]
    for b in bullets:
        raw = re.sub(r'^[•\-\*]\s*', '', b).strip()
        if ':' in raw:
            feature, rest = raw.split(':', 1)
            feature = feature.strip()
            if ' vs ' in rest or ' vs. ' in rest:
                vals = re.split(r'\s+vs\.?\s+', rest, flags=re.IGNORECASE)
                val_a = vals[0].strip()
                val_b = vals[1].strip() if len(vals) > 1 else "Not specified"
            else:
                val_a = rest.strip()
                val_b = rest.strip()
            rows.append([feature, val_a, val_b])

    if len(rows) <= 1:
        return None

    # Convert to table
    table_lines = [f"| {' | '.join(r)} |" for r in rows]
    table_lines.insert(1, "| --- | --- | --- |")
    return _build_table_from_markdown_lines(table_lines, styles)


def create_pdf_report(title, content_text, filename=None, query=None):
    """
    Builds a professional PDF document from generated content, automatically formatting tables.
    """
    output_dir = os.path.join(os.getcwd(), "exports")
    os.makedirs(output_dir, exist_ok=True)

    if not filename:
        clean_name = re.sub(r'[^a-zA-Z0-9_\- ]', '', title).strip().replace(' ', '_').lower()
        if not clean_name:
            clean_name = "report"
        timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
        filename = os.path.join(output_dir, f"{clean_name}_{timestamp}.pdf")
    else:
        if not os.path.isabs(filename):
            filename = os.path.join(output_dir, filename)

    doc = SimpleDocTemplate(
        filename,
        pagesize=letter,
        leftMargin=45,
        rightMargin=45,
        topMargin=45,
        bottomMargin=45
    )

    styles = getSampleStyleSheet()

    # Custom color palette
    NAVY = colors.HexColor("#1A365D")
    SLATE_BLUE = colors.HexColor("#2B6CB0")
    DARK_TEXT = colors.HexColor("#2D3748")
    BORDER_COLOR = colors.HexColor("#CBD5E0")

    # Typography Styles
    styles.add(ParagraphStyle(
        'DocTitle',
        parent=styles['Normal'],
        fontName='Helvetica-Bold',
        fontSize=18,
        leading=22,
        textColor=NAVY,
        spaceAfter=4
    ))

    styles.add(ParagraphStyle(
        'DocSubtitle',
        parent=styles['Normal'],
        fontName='Helvetica',
        fontSize=9,
        leading=12,
        textColor=colors.HexColor("#718096"),
        spaceAfter=10
    ))

    styles.add(ParagraphStyle(
        'SectionHeader',
        parent=styles['Normal'],
        fontName='Helvetica-Bold',
        fontSize=11,
        leading=14,
        textColor=SLATE_BLUE,
        spaceBefore=10,
        spaceAfter=3,
        keepWithNext=True
    ))

    styles.add(ParagraphStyle(
        'SubSectionHeader',
        parent=styles['Normal'],
        fontName='Helvetica-Bold',
        fontSize=9.5,
        leading=13,
        textColor=NAVY,
        spaceBefore=6,
        spaceAfter=2,
        keepWithNext=True
    ))

    styles.add(ParagraphStyle(
        'TableHeader',
        parent=styles['Normal'],
        fontName='Helvetica-Bold',
        fontSize=8.5,
        leading=11,
        textColor=colors.white
    ))

    styles.add(ParagraphStyle(
        'TableCell',
        parent=styles['Normal'],
        fontName='Helvetica',
        fontSize=8.5,
        leading=11.5,
        textColor=DARK_TEXT
    ))

    styles.add(ParagraphStyle(
        'BodyTextDark',
        parent=styles['Normal'],
        fontName='Helvetica',
        fontSize=9,
        leading=13,
        textColor=DARK_TEXT,
        spaceAfter=4
    ))

    styles.add(ParagraphStyle(
        'BulletItem',
        parent=styles['Normal'],
        fontName='Helvetica',
        fontSize=9,
        leading=12.5,
        textColor=DARK_TEXT,
        leftIndent=12,
        spaceAfter=2
    ))

    styles.add(ParagraphStyle(
        'SubBulletItem',
        parent=styles['Normal'],
        fontName='Helvetica',
        fontSize=8.5,
        leading=12,
        textColor=DARK_TEXT,
        leftIndent=24,
        spaceAfter=2
    ))

    story = []

    # Title & Metadata Banner
    clean_title = _clean_markdown_for_reportlab(title.replace("#", "").strip())
    story.append(Paragraph(clean_title, styles['DocTitle']))
    
    clean_q = _clean_markdown_for_reportlab(query or title)
    meta_info = f"<b>Topic:</b> {clean_q} &nbsp;|&nbsp; <b>Date:</b> {datetime.now().strftime('%B %d, %Y, %I:%M %p')}"
    story.append(Paragraph(meta_info, styles['DocSubtitle']))
    story.append(HRFlowable(width="100%", thickness=1.5, color=SLATE_BLUE, spaceBefore=0, spaceAfter=8))

    item_a, item_b = _extract_items_from_query(query or title)

    # Process content
    lines = content_text.split('\n')
    idx = 0
    while idx < len(lines):
        raw_line = lines[idx].strip()
        idx += 1

        if not raw_line:
            continue

        # Check if line is part of a markdown table (| ... |)
        if raw_line.startswith('|') and '|' in raw_line[1:]:
            table_lines = [raw_line]
            while idx < len(lines) and lines[idx].strip().startswith('|'):
                table_lines.append(lines[idx].strip())
                idx += 1
            table_flowable = _build_table_from_markdown_lines(table_lines, styles)
            if table_flowable:
                story.append(Spacer(1, 3))
                story.append(table_flowable)
                story.append(Spacer(1, 6))
            continue

        # Divider lines
        if set(raw_line).issubset({'━', '─', '-', '=', '_'}) and len(raw_line) > 5:
            continue

        # Main Section Headers
        is_header = raw_line.startswith('###') or raw_line.startswith('##') or any(
            raw_line.startswith(h) for h in [
                'QUICK VERDICT', 'KEY SPECIFICATIONS', 'DIFFERENCE TABLE', 'COMPARISON MATRIX',
                'WHICH ONE SHOULD YOU CHOOSE?', 'DIRECT ANSWER', 'KEY HIGHLIGHTS', 'BOTTOM LINE',
                'SOURCES', 'TOP HEADLINE', 'KEY UPDATES', 'IMPACT & OUTLOOK', 'NOTABLE CONFLICTS',
                'VERDICT', 'SPECIFICATIONS & DIFFERENCES'
            ]
        )
        if is_header:
            header_text = re.sub(r'^[#\s]+', '', raw_line)
            clean_h = _clean_markdown_for_reportlab(header_text)
            if clean_h:
                story.append(Paragraph(clean_h, styles['SectionHeader']))
                story.append(HRFlowable(width="100%", thickness=0.5, color=BORDER_COLOR, spaceBefore=1, spaceAfter=4))
            
                spec_bullets = []
                temp_idx = idx
                while temp_idx < len(lines):
                    next_line = lines[temp_idx].strip()
                    if not next_line:
                        temp_idx += 1
                        continue
                    # Skip horizontal divider lines
                    if set(next_line).issubset({'━', '─', '-', '=', '_'}) and len(next_line) > 5:
                        temp_idx += 1
                        continue
                    if next_line.startswith(('•', '-', '*')) and (
                        'vs' in next_line.lower() or ':' in next_line or '[' in next_line
                    ):
                        spec_bullets.append(next_line)
                        temp_idx += 1
                    else:
                        break
                if len(spec_bullets) >= 2:
                    table_obj = _convert_spec_bullets_to_table(spec_bullets, item_a, item_b, styles)
                    if table_obj:
                        story.append(Spacer(1, 2))
                        story.append(table_obj)
                        story.append(Spacer(1, 6))
                        idx = temp_idx
                        continue
            continue

        # Sub-headers like "Choose Option A if:"
        if raw_line.startswith(('Choose ', 'Option ')) and raw_line.endswith(':'):
            clean_sub_h = _clean_markdown_for_reportlab(raw_line)
            story.append(Paragraph(clean_sub_h, styles['SubSectionHeader']))
            continue

        # Sub-bullets
        if lines[idx - 1].startswith(('  •', '   •', '    •', '  -')):
            sub_text = _clean_markdown_for_reportlab(raw_line)
            story.append(Paragraph(f"• &nbsp; {sub_text}", styles['SubBulletItem']))
            continue

        # Regular Bullet items
        if raw_line.startswith(('•', '- ', '* ')):
            b_text = _clean_markdown_for_reportlab(raw_line)
            story.append(Paragraph(f"• &nbsp; {b_text}", styles['BulletItem']))
            continue

        # Numbered list items
        if re.match(r'^(\[\d+\]|\d+\.)\s+', raw_line):
            num_text = _clean_markdown_for_reportlab(raw_line)
            story.append(Paragraph(num_text, styles['BulletItem']))
            continue

        # Regular paragraph text
        p_text = _clean_markdown_for_reportlab(raw_line)
        if p_text:
            story.append(Paragraph(p_text, styles['BodyTextDark']))

    # Build the document
    doc.build(story, canvasmaker=NumberedCanvas)
    return os.path.abspath(filename)


def clear_all_pdfs(output_dir=None):
    """
    Deletes all generated PDF files from the exports/ directory.
    Returns: (count, list_of_filenames)
    """
    if not output_dir:
        output_dir = os.path.join(os.getcwd(), "exports")

    if not os.path.exists(output_dir):
        return 0, []

    deleted = []
    for f in os.listdir(output_dir):
        if f.lower().endswith(".pdf"):
            full_path = os.path.join(output_dir, f)
            try:
                os.remove(full_path)
                deleted.append(f)
            except Exception as e:
                print(f"⚠️  Could not delete {f}: {e}")

    return len(deleted), deleted
